import json, random, sys

def mc(prompt, options, explanation, code=None):
    return {"type": "multiple_choice", "prompt": prompt, "code": code, "options": options, "explanation": explanation}

def tf(prompt, answer, explanation, code=None):
    return {"type": "true_false", "prompt": prompt, "code": code, "answer": answer, "explanation": explanation}

def fb(prompt, options, explanation, accept=None, code=None):
    # prompt contém "___"; options é o banco de palavras (1ª = resposta)
    return {"type": "fill_blank", "prompt": prompt, "code": code, "options": options,
            "accept": accept or [], "explanation": explanation}

def L(title, concepts, questions):
    return {"title": title, "concepts": concepts, "questions": questions}

def U(title, description, lessons):
    return {"title": title, "description": description, "lessons": lessons}

