def build():
    course = {
        "schemaVersion": 1,
        "id": "node-backend",
        "title": "Dev Backend Node.js",
        "language": "pt-BR",
        "source": "https://claude.ai/artifact/6SxH8ytwepkHso4VEq7FSq",
        "units": [],
    }
    for ui, u in enumerate(UNITS):
        unit = {"id": f"u{ui}", "order": ui, "title": u["title"], "description": u["description"], "lessons": []}
        for li, l in enumerate(u["lessons"], 1):
            lid = f"u{ui}-l{li}"
            lesson = {"id": lid, "title": l["title"], "concepts": l["concepts"], "xp": 10, "questions": []}
            for qi, q in enumerate(l["questions"], 1):
                qid = f"{lid}-q{qi}"
                q = dict(q)
                out = {"id": qid, "type": q["type"], "prompt": q["prompt"]}
                if q.get("code"):
                    out["code"] = q["code"]
                if q["type"] in ("multiple_choice", "fill_blank"):
                    opts = q["options"]
                    assert len(opts) == len(set(opts)), qid
                    correct = opts[0]
                    shuffled = opts[:]
                    random.Random(qid).shuffle(shuffled)
                    out["options"] = shuffled
                    if q["type"] == "multiple_choice":
                        out["answer"] = shuffled.index(correct)
                    else:
                        assert "___" in q["prompt"], qid
                        out["answer"] = correct
                        out["accept"] = [correct] + q["accept"]
                else:
                    out["answer"] = q["answer"]
                out["explanation"] = q["explanation"]
                lesson["questions"].append(out)
            unit["lessons"].append(lesson)
        course["units"].append(unit)
    return course

